from django.urls import path

from apps.identity.views import (
    CsrfView,
    DeactivateView,
    EmailResendView,
    EmailVerifyView,
    LoginView,
    LogoutView,
    MfaConfirmView,
    MfaDisableView,
    MfaEnrollView,
    MfaVerifyView,
    PasswordChangeView,
    PasswordResetConfirmView,
    PasswordResetView,
    PhoneVerifyView,
    PhoneView,
    ProfileView,
    RefreshView,
    RegisterView,
    RevokeView,
)

urlpatterns = [
    path("csrf/", CsrfView.as_view(), name="auth-csrf"),
    path("register/", RegisterView.as_view(), name="auth-register"),
    path("login/", LoginView.as_view(), name="auth-login"),
    path("logout/", LogoutView.as_view(), name="auth-logout"),
    path("mfa/verify/", MfaVerifyView.as_view(), name="auth-mfa-verify"),
    path("mfa/enroll/", MfaEnrollView.as_view(), name="auth-mfa-enroll"),
    path("mfa/confirm/", MfaConfirmView.as_view(), name="auth-mfa-confirm"),
    path("mfa/disable/", MfaDisableView.as_view(), name="auth-mfa-disable"),
    path("me/", ProfileView.as_view(), name="auth-me"),
    path("email/verify/", EmailVerifyView.as_view(), name="auth-email-verify"),
    path("email/verification/", EmailResendView.as_view(), name="auth-email-resend"),
    path("password/reset/", PasswordResetView.as_view(), name="auth-password-reset"),
    path(
        "password/reset/confirm/",
        PasswordResetConfirmView.as_view(),
        name="auth-password-reset-confirm",
    ),
    path("password/change/", PasswordChangeView.as_view(), name="auth-password-change"),
    path("token/refresh/", RefreshView.as_view(), name="auth-token-refresh"),
    path("revoke/", RevokeView.as_view(), name="auth-revoke"),
    path("phone/", PhoneView.as_view(), name="auth-phone"),
    path("phone/verify/", PhoneVerifyView.as_view(), name="auth-phone-verify"),
    path("deactivate/", DeactivateView.as_view(), name="auth-deactivate"),
]
